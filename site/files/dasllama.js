/* dasLLAMA page — renders straight from the profiling JSON in files/dasllama/.
   The JSON is the single source of truth (generated by the dasLLAMA profiling
   suite); all ratios, win counts and rows are derived here, never hand-placed. */

(function () {
  'use strict';

  var DATA = {};

  function fmt(n, d) { return Number(n).toFixed(d == null ? 0 : d); }
  function tps(v) { return v > 0 ? fmt(v, 1) : '-'; }   // tok/s cell; '-' when unmeasured (matches gen_results cell_tps)
  // das / reference throughput ratio, or null when the reference wasn't measured
  // (matches gen_results cell_ratio: both sides must be > 0). Null never becomes a NaN cell.
  function ratio(das, ref) { return (ref > 0 && das > 0) ? das / ref : null; }

  // Records are reviewed before they land, but community rows are third-party text — escape
  // everything that reaches innerHTML.
  function esc(s) {
    return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  }

  /* ── per-model benchmark table (bench_records.json) ──────────────
     One row = one das configuration ÷ the matched llama.cpp build. A das number is
     never published without its yardstick, so a das run whose reference is missing
     (or whose flavor doesn't name a known category) yields no row at all — which is
     how a backend still being brought up stays off the table without a manual gate. */

  // Each category names the exact das flavor and the exact llama.cpp flavor it is measured
  // against. "stock" at -ngl 0 -nopo 1 is a genuine CPU number; without -nopo llama.cpp
  // op-offloads big-batch work to Metal and the row would not be CPU at all.
  var LANES = [
    { backend: 'cpu',    das: 'tuned', ref: 'clean-cpu', label: 'generic neon-64' },
    { backend: 'cpu',    das: 'accel', ref: 'stock',     label: 'cpu + AMX' },
    { backend: 'metal',  das: 'tuned', ref: 'stock',     label: 'as shipped' },
    { backend: 'vulkan', das: 'tuned', ref: 'stock',     label: 'vulkan' }
  ];

  var SORT = { key: 'size', desc: true };
  var FILTER = { model: '', box: '', lane: '' };
  var PAIRS = [];

  function tok(r, k) { return (r.tests && r.tests[k]) ? r.tests[k].tok_s : 0; }

  // A short machine label. hardware.cpu is auto-probed, so trim the x86 marketing suffix
  // the same way the ASR platform line does.
  function boxLabel(hw, box) {
    var cpu = (hw && hw.cpu) ? hw.cpu.replace('64-Core Processor', '').trim() : box;
    return cpu;
  }

  // Duplicate runs for one (model, box, category) shouldn't silently pick a lucky one:
  // prefer the most recent measurement, and keep input order as the tie-break.
  function newest(runs) {
    return runs.slice().sort(function (a, b) {
      return String(b.date || '').localeCompare(String(a.date || ''));
    })[0];
  }

  function buildPairs(recs) {
    var out = [];
    recs.forEach(function (m) {
      var boxes = {};
      (m.runs || []).forEach(function (r) { boxes[r.box] = true; });
      Object.keys(boxes).forEach(function (bx) {
        LANES.forEach(function (L) {
          function pick(engine, flavor) {
            var hits = (m.runs || []).filter(function (r) {
              return r.box === bx && r.backend === L.backend && r.flavor === flavor && r.engine === engine;
            });
            return hits.length ? newest(hits) : null;
          }
          var das = pick('das', L.das);
          var ref = pick('llama.cpp', L.ref);
          if (!das || !ref) return;                    // no yardstick → no row
          out.push({
            model: m.gguf.replace(/\.gguf$/, ''),
            gguf: m.gguf,
            arch: m.arch || '',
            quant: m.quant || '',
            params_b: m.params_b || 0,
            active_b: m.active_b || 0,
            note: m.note || '',
            size: m.size_bytes || 0,
            box: bx,
            boxName: boxLabel(das.hardware, bx),
            threads: das.threads || 0,
            lane: L.label,
            pp_das: tok(das, 'pp512'), pp_ref: tok(ref, 'pp512'),
            tg_das: tok(das, 'tg128'), tg_ref: tok(ref, 'tg128'),
            pp_ratio: ratio(tok(das, 'pp512'), tok(ref, 'pp512')),
            tg_ratio: ratio(tok(das, 'tg128'), tok(ref, 'tg128')),
            das: das, ref: ref
          });
        });
      });
    });
    return out;
  }

  function visible() {
    return PAIRS.filter(function (p) {
      return (!FILTER.model || p.model === FILTER.model) &&
             (!FILTER.box || p.box === FILTER.box) &&
             (!FILTER.lane || p.lane === FILTER.lane);
    });
  }

  function sortRows(rows) {
    var k = SORT.key, dir = SORT.desc ? -1 : 1;
    return rows.slice().sort(function (a, b) {
      var x = a[k], y = b[k];
      if (k === 'box') { x = a.boxName; y = b.boxName; }
      if (typeof x === 'string' || typeof y === 'string') {
        return String(x).localeCompare(String(y)) * dir;
      }
      // unmeasured (null) ratios sort last in either direction, never between real values
      if (x === null) return 1;
      if (y === null) return -1;
      if (x === y) return String(a.model).localeCompare(String(b.model));
      return (x - y) * dir;
    });
  }

  function ratioCell(r) {
    if (r === null) return '<td class="dl-num dl-dim">-</td>';
    var cls = r > 1.005 ? 'dl-win' : (r < 0.995 ? 'dl-loss' : '');   // tie: neutral, matching the caption
    return '<td class="dl-num ' + cls + '">' + fmt(r, 2) + '×</td>';
  }

  function receiptFor(p) {
    var lines = [];
    function side(tag, r) {
      var hw = r.hardware || {};
      lines.push('<b>' + tag + '</b>  $ ' + esc(r.cmd));
      var prov = [r.engine, r.sha ? '@ ' + r.sha : '', r.version || '', r.date || '',
        r.source && r.source !== 'official' ? r.source : ''].filter(Boolean).join(' · ');
      lines.push('        ' + esc(prov));
      if (r.tune) lines.push('        tune: ' + esc(r.tune));
      if (r.exec_fmt) lines.push('        executes: ' + esc(r.exec_fmt));
      lines.push('        ' + esc([hw.cpu, hw.total_cores ? hw.total_cores + ' cores' : '',
        hw.ram_gb ? hw.ram_gb + ' GB' : '', hw.gpu, hw.os].filter(Boolean).join(' · ')));
    }
    side('das      ', p.das);
    lines.push('');
    side('llama.cpp', p.ref);
    return lines.join('\n');
  }

  function renderBench() {
    var rows = sortRows(visible());
    var body = document.getElementById('bench-table-body');

    if (!rows.length) {
      body.innerHTML = '<tr><td class="dl-empty" colspan="10">No runs match these filters.</td></tr>';
    } else {
      body.innerHTML = rows.map(function (p, i) {
        // m.quant is the runtime activation mode (always q8), not the file's weight format —
        // showing it beside a "…-Q4_K_M" filename reads as a contradiction. The weight format is
        // in the model name, and exec_fmt in the receipt spells it out exactly.
        return '<tr class="dl-row" data-row="' + i + '">' +
            '<td class="dl-td-model">' + esc(p.model) +
              (p.arch ? ' <span class="dl-model-sub">' + esc(p.arch) + '</span>' : '') + '</td>' +
            '<td class="dl-box">' + esc(p.boxName) + '</td>' +
            '<td class="dl-lane">' + esc(p.lane) + '</td>' +
            '<td class="dl-num dl-dim">' + (p.size ? fmt(p.size / 1073741824, 1) : '-') + '</td>' +
            '<td class="dl-num dl-grp-start">' + tps(p.pp_das) + '</td>' +
            '<td class="dl-num dl-dim">' + tps(p.pp_ref) + '</td>' +
            ratioCell(p.pp_ratio) +
            '<td class="dl-num dl-grp-start">' + tps(p.tg_das) + '</td>' +
            '<td class="dl-num dl-dim">' + tps(p.tg_ref) + '</td>' +
            ratioCell(p.tg_ratio) +
          '</tr>' +
          '<tr hidden data-receipt="' + i + '"><td colspan="10">' +
            '<div class="dl-bench-receipt">' + receiptFor(p) + '</div></td></tr>';
      }).join('');

      body.querySelectorAll('[data-row]').forEach(function (el) {
        el.addEventListener('click', function () {
          var n = body.querySelector('[data-receipt="' + el.dataset.row + '"]');
          if (n) n.hidden = !n.hidden;
        });
      });
    }

    // win tally follows the current filter — it describes what is on screen, nothing more
    function tally(key) {
      var n = 0, seen = 0;
      rows.forEach(function (p) {
        if (p[key] === null) return;
        seen++;
        if (p[key] >= 0.995) n++;
      });
      return n + ' / ' + seen;
    }
    document.getElementById('bench-caption').innerHTML =
      '<span class="dl-win">' + tally('pp_ratio') + '</span> prefill · ' +
      '<span class="dl-win">' + tally('tg_ratio') + '</span> decode rows das ≥ llama.cpp' +
      ' &nbsp;·&nbsp; showing ' + rows.length + ' of ' + PAIRS.length + ' paired runs' +
      ' &nbsp;·&nbsp; click any row for its receipt';

    document.querySelectorAll('.js-bench-sort').forEach(function (th) {
      var on = th.dataset.sort === SORT.key;
      th.classList.toggle('is-sorted', on);
      th.classList.toggle('is-desc', on && SORT.desc);
    });
  }

  function fillFilters() {
    function distinct(get) {
      var seen = {}, out = [];
      PAIRS.forEach(function (p) { var v = get(p); if (v && !seen[v]) { seen[v] = 1; out.push(v); } });
      return out;
    }
    var opts = {
      model: distinct(function (p) { return p.model; }).sort(),
      box: distinct(function (p) { return p.box; }),
      lane: LANES.map(function (L) { return L.label; })
        .filter(function (l) { return PAIRS.some(function (p) { return p.lane === l; }); })
    };
    var boxName = {};
    PAIRS.forEach(function (p) { boxName[p.box] = p.boxName; });

    document.querySelectorAll('.js-bench-filter').forEach(function (sel) {
      var f = sel.dataset.field;
      var all = f === 'model' ? 'all models' : (f === 'box' ? 'all machines' : 'all categories');
      sel.innerHTML = '<option value="">' + all + '</option>' +
        opts[f].map(function (v) {
          return '<option value="' + esc(v) + '">' + esc(f === 'box' ? boxName[v] : v) + '</option>';
        }).join('');
      sel.addEventListener('change', function () { FILTER[f] = sel.value; renderBench(); });
    });

    document.querySelectorAll('.js-bench-sort').forEach(function (th) {
      th.addEventListener('click', function () {
        var k = th.dataset.sort;
        // first click on a new column: numbers start high-to-low, text starts A-to-Z
        if (SORT.key === k) SORT.desc = !SORT.desc;
        else { SORT.key = k; SORT.desc = (k !== 'model' && k !== 'box' && k !== 'lane'); }
        renderBench();
      });
    });

    document.querySelector('.js-bench-reset').addEventListener('click', function () {
      FILTER.model = FILTER.box = FILTER.lane = '';
      document.querySelectorAll('.js-bench-filter').forEach(function (s) { s.value = ''; });
      SORT = { key: 'size', desc: true };
      renderBench();
    });
  }

  /* ── ASR scoreboard ────────────────────────────────────────── */
  var ASR_FEATURE = {
    m1: ['Parakeet-TDT v2', 'Whisper tiny'],
    zen2: ['Parakeet-TDT v2', 'Whisper large-v3-turbo']
  };

  function renderASR() {
    var box = document.querySelector('.js-asr-box.is-active').dataset.box;
    var d = DATA['asr_' + box];
    var wanted = ASR_FEATURE[box];

    var html = wanted.map(function (name) {
      var t = d.tests.find(function (x) { return x.model === name; });
      if (!t) return '';
      var refTool = t.references[0]; // primary cli reference
      // max speedup across buckets for bar scaling
      var maxSpeed = 0;
      t.buckets.forEach(function (b) {
        var ref = b.refs.find(function (r) { return r.tool === refTool; });
        if (ref) maxSpeed = Math.max(maxSpeed, ref.ms / b.das_ms);
      });
      var rowsHTML = t.buckets.map(function (b) {
        var ref = b.refs.find(function (r) { return r.tool === refTool; });
        if (!ref) return '';
        var speed = ref.ms / b.das_ms;      // >1 = das faster
        var xrt = (b.audio_s * 1000) / b.das_ms;
        var w = Math.max(4, (speed / maxSpeed) * 100);
        return '<div class="dl-asr-row">' +
          '<div class="dl-asr-row__file">' + b.wav + '<span class="dl-asr-row__dur">' + fmt(b.audio_s) + 's</span></div>' +
          '<div class="dl-asr-row__track"><div class="dl-asr-row__fill" style="width:' + w + '%"></div></div>' +
          '<div class="dl-asr-row__speed">' + fmt(speed, 2) + '× <span class="dl-asr-row__xrt">' + fmt(xrt) + '× RT</span></div>' +
          '</div>';
      }).join('');
      return '<div class="dl-asr-model">' +
        '<div class="dl-asr-model__head"><span class="dl-asr-model__name">' + t.model + '</span>' +
        '<span class="dl-asr-model__ref">das vs ' + refTool + '</span></div>' +
        rowsHTML + '</div>';
    }).join('');

    document.getElementById('asr-models').innerHTML = html;
    document.getElementById('asr-plat').textContent =
      d.platform.cpu.replace('64-Core Processor', '').trim() + ' · ' + d.platform.threads + ' threads';
  }

  /* ── Audio-chat blowout callouts (M1, the biggest wins) ─────── */
  function renderAudioChat() {
    var d = DATA.asr_m1;
    function best(model, wav) {
      var t = d.tests.find(function (x) { return x.model === model; });
      var b = t.buckets.find(function (x) { return x.wav === wav; });
      var ref = b.refs[0];
      return { speed: ref.ms / b.das_ms, das: b.das_ms, ref: ref.ms, audio: b.audio_s };
    }
    var q = best('Qwen3-Omni-30B audio', 'jfk.wav');
    var g = best('Gemma-4 E2B audio', 'gemma4a_test2.wav');
    var cards = [
      { n: fmt(q.speed, 1) + '×', t: 'Qwen3-Omni-30B, audio in', s: 'vs llama-mtmd-cli, CPU-only · ' + fmt(q.das) + ' ms vs ' + fmt(q.ref) + ' ms' },
      { n: fmt(g.speed, 1) + '×', t: 'Gemma-4 E2B, audio in', s: 'vs llama-mtmd-cli, CPU-only · ' + fmt(g.das) + ' ms vs ' + fmt(g.ref) + ' ms' }
    ];
    document.getElementById('audiochat-cards').innerHTML = cards.map(function (c) {
      return '<div class="dl-blowout"><div class="dl-blowout__n">' + c.n + '</div>' +
        '<div class="dl-blowout__t">' + c.t + '</div>' +
        '<div class="dl-blowout__s">' + c.s + '</div></div>';
    }).join('');
  }

  /* ── wiring ─────────────────────────────────────────────────── */
  function wireToggle(sel, cb) {
    document.querySelectorAll(sel).forEach(function (btn) {
      btn.addEventListener('click', function () {
        var group = btn.parentElement;
        group.querySelectorAll(sel).forEach(function (b) { b.classList.toggle('is-active', b === btn); });
        cb();
      });
    });
  }

  Promise.all([
    fetch('files/dasllama/profile_asr_m1.json').then(function (r) { return r.json(); }),
    fetch('files/dasllama/profile_asr_zen2.json').then(function (r) { return r.json(); })
  ]).then(function (res) {
    DATA.asr_m1 = res[0]; DATA.asr_zen2 = res[1];
    renderASR();
    renderAudioChat();
    wireToggle('.js-asr-box', renderASR);
  }).catch(function (e) {
    document.getElementById('asr-models').innerHTML =
      '<div style="color:var(--red);font-family:var(--font-mono);font-size:13px">Could not load profiling data: ' + e + '</div>';
  });

  // the record table loads independently — the section stays hidden until records ship
  fetch('files/dasllama/bench_records.json')
    .then(function (r) { if (!r.ok) throw new Error(r.status); return r.json(); })
    .then(function (j) {
      PAIRS = buildPairs(j);
      if (!PAIRS.length) return;              // records exist but nothing is paired yet
      document.getElementById('bench').hidden = false;
      fillFilters();
      renderBench();
    })
    .catch(function () { /* no records yet */ });
})();
